export const DopplerQuiz: React.FC = () => {
  const [selectedAnswers, setSelectedAnswers] = useState<Record<number, number>>({});

  const handleSelectOption = (questionId: number, optionIndex: number) => {
    if (selectedAnswers[questionId] !== undefined) return;
    setSelectedAnswers((prev) => ({
      ...prev,
      [questionId]: optionIndex,
    }));
  };

  const handleRestart = () => {
    setSelectedAnswers({});
  };

  const answeredCount = Object.keys(selectedAnswers).length;
  const isFinished = answeredCount === QUIZ_QUESTIONS.length;

  const score = QUIZ_QUESTIONS.reduce((acc, q) => {
    return selectedAnswers[q.id] === q.correctIndex ? acc + 1 : acc;
  }, 0);

  const percentage = Math.round((score / QUIZ_QUESTIONS.length) * 100);

  return (
    <div className="bg-[#101D30] rounded-xl border border-[#26364D] p-5 shadow-xl flex flex-col gap-4">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-[#26364D]">
        <div className="flex items-center gap-2.5">
          <div className="p-2 rounded-lg bg-[#A78BFA]/15 border border-[#A78BFA]/30 text-[#A78BFA]">
            <HelpCircle className="w-5 h-5" />
          </div>
          <div>
            <h3 className="text-base font-extrabold text-[#F1F5F9] uppercase tracking-wide">
              Doppler Effect Knowledge Evaluation Quiz
            </h3>
            <p className="text-xs text-[#94A3B8]">
              10 comprehensive multiple-choice questions for Class 11 &amp; Class 12 physics
            </p>
          </div>
        </div>

        <div className="flex items-center gap-3">
          <span className="text-xs font-mono font-bold text-[#38BDF8] bg-[#17263B] px-2.5 py-1 rounded border border-[#26364D]">
            Score: {score} / {QUIZ_QUESTIONS.length} ({percentage}%)
          </span>
          <button
            onClick={handleRestart}
            className="flex items-center gap-1.5 px-3 py-1 text-xs text-[#F1F5F9] bg-[#17263B] hover:bg-[#1E334D] rounded-lg border border-[#26364D] transition-colors cursor-pointer"
          >
            <RotateCcw className="w-3.5 h-3.5 text-[#94A3B8]" />
            <span>Restart Quiz</span>
          </button>
        </div>
      </div>

      {/* Completion Banner */}
      {isFinished && (
        <div className="p-4 rounded-xl bg-gradient-to-r from-[#10B981]/20 via-[#38BDF8]/20 to-[#A78BFA]/20 border border-[#34D399]/40 flex items-center justify-between gap-4">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-lg bg-[#10B981]/20 text-[#34D399]">
              <Award className="w-6 h-6" />
            </div>
            <div>
              <h3 className="text-sm font-bold text-[#F1F5F9]">Quiz Completed!</h3>
              <p className="text-xs text-[#94A3B8]">
                You scored <strong className="text-[#34D399]">{score}</strong> out of{' '}
                <strong className="text-[#F1F5F9]">{QUIZ_QUESTIONS.length}</strong> ({percentage}%).
              </p>
            </div>
          </div>

          <button
            onClick={handleRestart}
            className="px-3.5 py-1.5 text-xs font-bold text-[#07111F] bg-[#38BDF8] hover:bg-[#7DD3FC] rounded-lg transition-colors cursor-pointer shrink-0 shadow-xs"
          >
            Retake Quiz
          </button>
        </div>
      )}

      {/* Questions List */}
      <div className="space-y-4">
        {QUIZ_QUESTIONS.map((q, qIdx) => {
          const userAnswer = selectedAnswers[q.id];
          const hasAnswered = userAnswer !== undefined;
          const isCorrect = userAnswer === q.correctIndex;

          return (
            <div
              key={q.id}
              className={`p-4 rounded-xl border transition-all ${
                hasAnswered
                  ? isCorrect
                    ? 'bg-[#10B981]/10 border-[#10B981]/40'
                    : 'bg-[#FB7185]/10 border-[#FB7185]/40'
                  : 'bg-[#17263B] border-[#26364D]'
              }`}
            >
              <div className="flex items-start gap-2.5 mb-3">
                <span className="font-mono text-xs font-bold text-[#38BDF8] shrink-0">
                  Q{qIdx + 1}.
                </span>
                <h4 className="text-xs font-bold text-[#F1F5F9] leading-relaxed">{q.question}</h4>
              </div>

              {/* Options */}
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 pl-6">
                {q.options.map((opt, optIdx) => {
                  let optStyle =
                    'bg-[#101D30] border-[#26364D] text-[#F1F5F9] hover:border-[#38BDF8]/60 hover:bg-[#1E334D]';

                  if (hasAnswered) {
                    if (optIdx === q.correctIndex) {
                      optStyle = 'bg-[#10B981]/20 border-[#34D399] text-[#34D399] font-bold';
                    } else if (optIdx === userAnswer) {
                      optStyle = 'bg-[#FB7185]/20 border-[#FB7185] text-[#FB7185] line-through';
                    } else {
                      optStyle = 'bg-[#101D30]/60 border-[#26364D] text-[#64748B]';
                    }
                  }

                  return (
                    <button
                      key={optIdx}
                      disabled={hasAnswered}
                      onClick={() => handleSelectOption(q.id, optIdx)}
                      className={`text-left p-3 rounded-lg border text-xs transition-all cursor-pointer disabled:cursor-default flex items-center justify-between gap-2 ${optStyle}`}
                    >
                      <span>{opt}</span>
                      {hasAnswered && optIdx === q.correctIndex && (
                        <CheckCircle2 className="w-4 h-4 text-[#34D399] shrink-0" />
                      )}
                      {hasAnswered && optIdx === userAnswer && !isCorrect && (
                        <XCircle className="w-4 h-4 text-[#FB7185] shrink-0" />
                      )}
                    </button>
                  );
                })}
              </div>

              {/* Immediate Feedback & Explanation */}
              {hasAnswered && (
                <div
                  className={`mt-3 pl-6 pt-2.5 border-t text-xs leading-relaxed ${
                    isCorrect
                      ? 'border-[#10B981]/30 text-[#34D399]'
                      : 'border-[#FB7185]/30 text-[#FB7185]'
                  }`}
                >
                  <p>
                    <strong className="text-[#F1F5F9]">Explanation: </strong>
                    {q.explanation}
                  </p>
                </div>
              )}
            </div>
          );
        })}
      </div>
    </div>
  );
};
